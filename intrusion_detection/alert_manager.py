class AlertManager:
    """
    Central manager for storing and displaying
    intrusion detection alerts.
    """

    def __init__(self):
        self.alerts = []

    def add_alert(self, alert):
        """
        Add a new alert to the alert list.

        Args:
            alert (dict): Alert generated by a detector.
        """

        if alert is not None:
            self.alerts.append(alert)

    def get_alerts(self):
        """
        Return all stored alerts.

        Returns:
            list: List of alert dictionaries.
        """

        return self.alerts

    def get_alert_count(self):
        """
        Return the total number of stored alerts.

        Returns:
            int: Number of alerts.
        """

        return len(self.alerts)

    def display_alert(self, alert):
        """
        Display a single alert in a readable format.
        """

        if alert is None:
            return

        print("\n" + "=" * 50)
        print("            NETGUARD SECURITY ALERT")
        print("=" * 50)
        print(f"Alert Type       : {alert.get('alert_type', 'UNKNOWN')}")
        print(f"Source IP        : {alert.get('source_ip', 'UNKNOWN')}")
        print(f"Severity         : {alert.get('severity', 'UNKNOWN')}")
        print(f"Timestamp        : {alert.get('timestamp', 'UNKNOWN')}")

        if "port_count" in alert:
            print(f"Port Count       : {alert['port_count']}")

        if "connection_count" in alert:
            print(f"Connection Count : {alert['connection_count']}")

        print("=" * 50)

    def display_all_alerts(self):
        """
        Display every stored alert.
        """

        if not self.alerts:
            print("No security alerts detected.")
            return

        for alert in self.alerts:
            self.display_alert(alert)