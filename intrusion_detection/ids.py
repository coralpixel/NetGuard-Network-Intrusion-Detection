from intrusion_detection.port_scan import PortScanDetector
from intrusion_detection.traffic_detection import TrafficAnomalyDetector
from intrusion_detection.alert_manager import AlertManager


class NetGuardIDS:
    """
    Main controller for the NetGuard intrusion detection system.

    Connects the port scan detector, traffic anomaly detector,
    and alert manager.
    """

    def __init__(
        self,
        port_threshold=10,
        traffic_threshold=20,
        time_window=10
    ):
        self.port_scan_detector = PortScanDetector(
            port_threshold=port_threshold,
            time_window=time_window
        )

        self.traffic_detector = TrafficAnomalyDetector(
            traffic_threshold=traffic_threshold,
            time_window=time_window
        )

        self.alert_manager = AlertManager()

    def process_connection(self, source_ip, destination_port):
        """
        Process a network connection through the IDS detectors.

        Args:
            source_ip (str): IP address initiating the connection.
            destination_port (int): Destination port contacted.

        Returns:
            list: Alerts generated by the detectors.
        """

        alerts = []

        # Check for port scanning
        port_scan_alert = self.port_scan_detector.record_connection(
            source_ip,
            destination_port
        )

        if port_scan_alert:
            self.alert_manager.add_alert(port_scan_alert)
            alerts.append(port_scan_alert)

        # Check for unusually high traffic
        traffic_alert = self.traffic_detector.record_connection(
            source_ip
        )

        if traffic_alert:
            self.alert_manager.add_alert(traffic_alert)
            alerts.append(traffic_alert)

        return alerts

    def get_alerts(self):
        """Return all alerts generated by the IDS."""

        return self.alert_manager.get_alerts()

    def get_alert_count(self):
        """Return the total number of generated alerts."""

        return self.alert_manager.get_alert_count()

    def display_alerts(self):
        """Display all alerts through the Alert Manager."""

        self.alert_manager.display_all_alerts()